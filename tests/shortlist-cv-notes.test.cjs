const assert=require('node:assert/strict');
const {interviewTips,render,rows}=require('../src/static/js/shortlisting.js');
const first={id:'a',vacancy_id:1,name:'Candidate A',position:'Developer',matched_required:['JavaScript'],to_confirm:['SQL'],projects:['Inventory app'],years:0};
const second={id:'b',vacancy_id:2,name:'Candidate B',position:'Analyst',matched_required:['Excel'],to_confirm:[],projects:['Forecast review'],years:5};
const notes=interviewTips(first);
assert.deepEqual(notes[0].evidence,['JavaScript']);
assert.deepEqual(notes[1].evidence,['SQL']);
assert.deepEqual(notes[2].evidence,['Inventory app']);
assert.deepEqual(notes[3].evidence,['0']);
assert.match(notes[1].description,/do not treat an omission as inability/);
assert.doesNotMatch(JSON.stringify(interviewTips(second)),/JavaScript|Inventory app/);
for(const years of [null,undefined,'',NaN,-1])assert.deepEqual(interviewTips({years})[3].evidence,[]);
assert.match(interviewTips({})[2].description,/No project details/);
assert.deepEqual(interviewTips({projects:[null,{},' Project ','Project']})[2].evidence,['Project']);
assert.equal(rows([first,second],{'1|a':'Shortlist','2|b':'Shortlist'},'1').length,1);
const elements={shortlistCandidates:{querySelectorAll:()=>[]},shortlistVacancy:{value:''},shortlistStatus:{}};
global.fetch=()=>{throw Error('CV notes must not request a model');};
render({document:{getElementById:id=>elements[id]},candidates:[{...first,projects:['<img src=x onerror=alert(1)>']}],vacancies:[{id:1,title:'Developer'}],decisions:{'1|a':'Shortlist'},onGenerate:()=>{throw Error('Generation must not run');}});
const html=elements.shortlistCandidates.innerHTML;
assert.match(html,/CV-based interview notes/);
assert.match(html,/JavaScript/);
assert.match(html,/&lt;img src=x onerror=alert\(1\)&gt;/);
assert.doesNotMatch(html,/<img|Auto generate|data-question-status|regenerate/);
console.log('Candidate-specific CV notes, missing evidence, vacancy isolation and escaped rendering: passed.');
